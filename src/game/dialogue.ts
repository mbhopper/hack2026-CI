export const questionKey = (suspect: string, question: string) => `${suspect}:${question}`

/** Есть ли у детектива всё, чтобы задать вопрос */
export function canAsk(state: GameState, question: Question) {
  return (question.needs ?? []).every((id) => state.found.includes(id) || state.facts.includes(id))
}
