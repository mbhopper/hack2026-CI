/**
 * Вопросы на допросах. Часть открывается только с уликой или чужим
 * показанием в блокноте: так допросы и осмотр подталкивают друг друга.
 */

export interface Line {
  /** detective — реплика игрока, иначе говорит подозреваемый */
  who: 'detective' | 'suspect'
  text: string
}

export interface Question {
  id: string
  /** Что спрашивает детектив, текст кнопки */
  ask: string
  answer: Line[]
  /** id улик и показаний, без которых вопрос не задать */
  needs?: string[]
  /** Показания, которые попадут в блокнот */
  facts?: string[]
}

